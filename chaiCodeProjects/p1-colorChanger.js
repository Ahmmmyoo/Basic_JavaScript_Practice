function randomHexColor() {
  return (
    '#' +
    Math.floor(Math.random() * 0xffffff)
      .toString(16)
      .padStart(6, '0')
  );
}

function makeSpan() {
  const span = document.createElement('span');
  const rHC = randomHexColor();
  span.setAttribute('id', rHC);
  span.setAttribute('class', 'box');
  span.appendChild(document.createTextNode(rHC));
  span.style.backgroundColor = rHC;
  span.style.margin = '5px';
  document.querySelector('.box').append(span);
  // console.log(span);
}

